import { phoneDigits, personChanges, needsReason, changesPayload, auditAction } from '../../src/lib/personEdits.js';
import { personMatches } from '../../src/components/peopleList.jsx';
let fails = 0;
const ok = (c, m) => { if (c) console.log('ok', m); else { fails++; console.log('FAIL', m); } };
ok(phoneDigits('(214) 555-0187') === '2145550187', 'formats to digits');
ok(phoneDigits('+1 214 555 0187') === '2145550187', 'drops the leading 1');
ok(phoneDigits('') === '' && phoneDigits('  ') === '', 'blank is empty');
ok(phoneDigits('555-0187') === null && phoneDigits('22145550187') === null, 'not 10 digits is bad');
const before = { display_name: 'Riley "Dynamite" Park', phone: '2145550187', role: 'advisor', manager_id: 'd', hierarchy_tier: 'UA' };
const names = { d: 'Dana Brooks', m: 'Morgan Lee' };
const nameOf = id => names[id] || '';
ok(personChanges(before, { ...before, display_name: ' Riley  "Dynamite"  Park ', phone: '(214) 555-0187', manager_id: 'd' }, nameOf).length === 0, 'spaces and phone formatting are not changes');
let ch = personChanges(before, { ...before, display_name: 'Riley Park' }, nameOf);
ok(ch.length === 1 && ch[0].key === 'display_name' && !needsReason(ch), 'name only: no reason needed');
ch = personChanges(before, { ...before, phone: '' }, nameOf);
ok(ch.length === 1 && ch[0].to === 'none' && !needsReason(ch), 'removing the phone: no reason');
ch = personChanges(before, { ...before, phone: '555' }, nameOf);
ok(ch.length === 0, 'a half-typed phone is not a change yet');
ch = personChanges(before, { ...before, hierarchy_tier: 'FA' }, nameOf);
ok(ch.length === 1 && ch[0].label === 'Comp level' && ch[0].from === 'UA' && ch[0].to === 'FA' && needsReason(ch), 'comp level needs a reason');
ch = personChanges(before, { ...before, manager_id: 'm', role: 'manager' }, nameOf);
ok(ch.length === 2 && needsReason(ch) && ch.find(c => c.key === 'manager_id').from === 'Dana Brooks' && ch.find(c => c.key === 'manager_id').to === 'Morgan Lee', 'reports-to by name');
ok(ch.find(c => c.key === 'role').to === 'Manager', 'role by label');
ch = personChanges({ ...before, manager_id: null }, { ...before, manager_id: '' }, nameOf);
ok(ch.length === 0, 'null and empty upline are the same');
const draft = { ...before, display_name: ' Riley  Park ', phone: '(214) 555-0100', hierarchy_tier: '', manager_id: 'm' };
const p = changesPayload(personChanges(before, draft, nameOf), draft);
ok(JSON.stringify(p) === JSON.stringify({ display_name: 'Riley Park', phone: '2145550100', manager_id: 'm', hierarchy_tier: '' }), 'payload has only what changed: ' + JSON.stringify(p));
ok(auditAction('Changed hierarchy tier') === 'Changed comp level' && auditAction('Promoted') === 'Promoted', 'old log wording reads as comp level');
ok(personMatches({ display_name: 'Riley Park', phone: '2145550187' }, '555-01'), 'search finds part of a phone number');
ok(!personMatches({ display_name: 'Riley Park', phone: '2145550187' }, '55'), 'two digits is too short');
ok(!personMatches({ display_name: 'Riley Park' }, '214'), 'no phone, no phone match');
console.log(fails ? `${fails} FAILED` : 'ALL PERSON EDIT UNIT TESTS PASSED');
process.exit(fails ? 1 : 0);
